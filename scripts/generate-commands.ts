import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { allCommands } from '../src/commands/index.js';
import { commandSpec, operationKey, operations } from './openapi.js';

const args = process.argv.slice(2);
const check = args.includes('--check');
const spec = JSON.parse(await readFile(args.find(a => a !== '--check') ?? new URL('../spec/api_v2.json', import.meta.url), 'utf8'));
// Excluding generated definitions makes regeneration deterministic, including updates to their schemas.
const existing = new Set(allCommands.filter(c => !c.generated).map(c => operationKey(c.endpoint.method, c.endpoint.path)));
const missing = operations(spec).filter(o => !existing.has(operationKey(o.method, o.path)));
const directory = new URL('../src/commands/generated/', import.meta.url);
if (!check) await mkdir(directory, { recursive: true });
async function emit(name: string, source: string) {
  const target = new URL(name, directory);
  source = source.replace(/\u2014/g, '-');
  if (check) {
    if (await readFile(target, 'utf8').catch(() => '') !== source) throw new Error(`Generated file out of date: ${target.pathname}`);
  } else await writeFile(target, source);
}
const imports: string[] = [];
const names = new Set(allCommands.filter(c => !c.generated).map(c => c.name));
for (const op of missing) {
  const definition = commandSpec(spec, op);
  if (names.has(definition.name)) throw new Error(`Command collision: ${definition.name}`);
  names.add(definition.name);
  const name = definition.name;
  const source = `// Generated by scripts/generate-commands.ts. Review changes before committing.\nimport { createSpecCommand } from '../../core/spec-command.js';\n\nexport const ${name} = createSpecCommand(${JSON.stringify(definition, null, 2)});\n`;
  await emit(`${name}.ts`, source);
  imports.push(`import { ${name} } from './${name}.js';`);
}
await emit('index.ts', `${imports.join('\n')}\n\nexport const generatedCommands = [\n${missing.map(o => `  ${commandSpec(spec, o).name},`).join('\n')}\n];\n`);
console.log(`Generated ${missing.length} command definitions`);
